// db/*.sql → lib/schema.ts, so a fresh studio makes its own tables (lib/db.ts ensureSchema). Run after changing a
// migration: node scripts/gen-schema.mjs (every statement must be safe to run again: IF NOT EXISTS).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const dir = new URL("../db/", import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const stmts = files.flatMap((f) => readFileSync(new URL(f, dir), "utf8")
  .split("\n").filter((l) => !l.trim().startsWith("--")).join("\n")
  .split(/;\s*(?:\n|$)/).map((s) => s.trim()).filter(Boolean));
writeFileSync(new URL("../lib/schema.ts", import.meta.url),
  `// Generated by scripts/gen-schema.mjs from ${files.join(", ")}. Don't edit: change db/ and run it again.\nexport const SCHEMA: string[] = ${JSON.stringify(stmts, null, 2)};\n`);
console.log(`${stmts.length} statements from ${files.length} files`);
